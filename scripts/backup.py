#!/usr/bin/env python3
"""Consistent SQLite snapshot, encrypted local backups. Run as root."""
from pathlib import Path
import datetime,os,sqlite3,subprocess,tempfile
root=Path('/data/webleads');out=root/'backups';out.mkdir(exist_ok=True);os.chmod(out,0o700)
with tempfile.TemporaryDirectory(prefix='webleads-backup-') as temp:
 snapshot=Path(temp)/'webleads.sqlite';src=sqlite3.connect(root/'storage/webleads.sqlite');dst=sqlite3.connect(snapshot);src.backup(dst);dst.close();src.close()
 target=out/('webleads-'+datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ')+'.tar.gz.enc')
 items=['webleads.sqlite','-C',str(root),'runtime.env']
 if (root/'owner-activation.url').exists():items.append('owner-activation.url')
 if (root/'tunnel-before.json').exists():items.append('tunnel-before.json')
 tar=subprocess.Popen(['tar','-czf','-','-C',temp]+items,stdout=subprocess.PIPE)
 with target.open('wb') as output:subprocess.run(['openssl','enc','-aes-256-cbc','-pbkdf2','-salt','-pass','file:'+str(root/'backup.key')],stdin=tar.stdout,stdout=output,check=True)
 tar.stdout.close();assert tar.wait()==0;os.chmod(target,0o600)
 # Delete only backup files generated by this script, retaining newest 14.
 for old in sorted(out.glob('webleads-*.tar.gz.enc'))[:-14]:old.unlink()
 print('Encrypted WebLeads backup created')
